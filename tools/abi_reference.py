#!/usr/bin/env python3
"""Generate the C ABI reference from the public headers, or check that it is current.

The headers are the source of truth: each comment block documents the declarations
that follow it until a blank line. Constants, records, and functions are rendered in
header order so the reference reads like the headers, without their line noise.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADERS = (
  ("bemo.h", "Bemo metadata and native allocation",
   "Query the metadata ABI before resolving anything else. Capabilities are additive bits; "
   "unknown bits must be ignored."),
  ("elide_transport.h", "Elide transport ABI 3",
   "The transport boundary shared by the FFM and Native Image bindings. Handles are opaque, "
   "never reused, and zero is invalid; negative status codes report failure."),
)
OUTPUT = ROOT / "docs/reference/c-abi.md"

DECLARATION = re.compile(r"^([A-Za-z_][\w\s\*]*?[\s\*])(\w+)\((.*)\);$")


def comment_text(lines):
  text = " ".join(line.strip() for line in lines)
  text = re.sub(r"^/\*+|\*+/$", "", text.strip()).strip()
  text = re.sub(r"\s*\*\s+", " ", text)
  return re.sub(r"\s+", " ", text).strip()


def parse(text):
  """Yield ('define'|'struct'|'group', payload) items in header order."""
  items = []
  lines = text.splitlines()
  comment, pending, index = None, [], 0
  group = None

  def close_group():
    nonlocal group
    if group and group["functions"]:
      items.append(("group", group))
    group = None

  while index < len(lines):
    raw = lines[index]
    line = raw.strip()
    if line.startswith("/*"):
      block = [line]
      while not block[-1].endswith("*/"):
        index += 1
        block.append(lines[index].strip())
      text_block = comment_text(block)
      if "Copyright" in text_block or "SPDX" in text_block:
        index += 1
        continue
      close_group()
      comment = text_block
    elif not line:
      close_group()
      comment = None
    elif line.startswith("#define"):
      name, _, value = line[len("#define"):].strip().partition(" ")
      if value:
        items.append(("define", (name, value.strip(), comment)))
      comment = None
    elif line.startswith("#") or line in ('extern "C" {', "}"):
      pass
    elif line.startswith("typedef struct"):
      fields = []
      index += 1
      while not lines[index].strip().startswith("}"):
        field = lines[index].strip().rstrip(";")
        if field:
          fields.append(field)
        index += 1
      name = lines[index].strip().strip("};").strip()
      close_group()
      items.append(("struct", (name, fields, comment)))
      comment = None
    else:
      # Join wrapped declarations.
      declaration = line
      while not declaration.endswith(";") and index + 1 < len(lines):
        index += 1
        declaration += " " + lines[index].strip()
      match = DECLARATION.match(re.sub(r"\s+", " ", declaration))
      if match and not declaration.startswith(("#", "typedef", "extern")):
        _, name, _ = match.groups()
        signature = re.sub(r"\s+", " ", declaration).removesuffix(";")
        if group is None:
          group = {"comment": comment, "functions": []}
          comment = None
        group["functions"].append((name, re.sub(r"\s+", " ", signature)))
      elif declaration.startswith("typedef"):
        close_group()
        items.append(("typedef", (re.sub(r"\s+", " ", declaration), comment)))
        comment = None
    index += 1
  close_group()
  return items


def render():
  out = [
    "# C ABI reference",
    "",
    "<!-- Generated by tools/abi_reference.py from include/*.h. Do not edit; run",
    "     `python3 tools/abi_reference.py` after changing a header. -->",
    "",
    "Both Java bindings and Rust embedders reach Bemo through these C declarations.",
    "Read [handles and ownership](../guide/abi-concepts.md) first; this page lists",
    "every constant, record, and function with the contract text from the headers.",
    "",
  ]
  for header, title, summary in HEADERS:
    items = parse((ROOT / "include" / header).read_text())
    functions = sum(len(payload["functions"]) for kind, payload in items if kind == "group")
    out += [f"## {title}", "", f"Header: [`include/{header}`](../../include/{header}). "
            f"{functions} functions.", "", summary, ""]
    defines = [payload for kind, payload in items if kind == "define"]
    if defines:
      out += ["### Constants", "", "| Name | Value |", "| --- | --- |"]
      out += [f"| `{name}` | `{value}` |" for name, value, _ in defines]
      out.append("")
    records = [payload for kind, payload in items if kind in ("struct", "typedef")]
    if records:
      out += ["### Types", ""]
      for payload in records:
        if len(payload) == 3:
          name, fields, comment = payload
          out += [f"#### `{name}`", ""]
          if comment:
            out += [comment, ""]
          out += ["```c", "typedef struct {", *[f"  {field};" for field in fields], f"}} {name};", "```", ""]
        else:
          declaration, comment = payload
          if comment:
            out += [comment, ""]
          out += ["```c", declaration, "```", ""]
    out += ["### Functions", ""]
    for kind, payload in items:
      if kind != "group":
        continue
      names = [name for name, _ in payload["functions"]]
      out.append("#### " + ", ".join(f"`{name}`" for name in names))
      out.append("")
      if payload["comment"]:
        out += [payload["comment"], ""]
      out += ["```c", *[signature + ";" for _, signature in payload["functions"]], "```", ""]
  return "\n".join(out).rstrip() + "\n"


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--check", action="store_true", help="Fail if the committed reference is stale")
  args = parser.parse_args()
  text = render()
  if args.check:
    if not OUTPUT.exists() or OUTPUT.read_text() != text:
      sys.exit("docs/reference/c-abi.md is stale; run python3 tools/abi_reference.py")
    return
  OUTPUT.parent.mkdir(parents=True, exist_ok=True)
  OUTPUT.write_text(text)
  print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
  main()
